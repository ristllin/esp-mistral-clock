def emit():
    out = []
    out.append("/* Generated by tools/gen_sprite_art.py -- do not edit by hand.")
    out.append(" * Palette-indexed sprite maps for src/scene.c; 0 = transparent,")
    out.append(" * other values are P_* slots from src/scene.h. */")
    out.append("#ifndef CLOCK_SCENE_ART_H")
    out.append("#define CLOCK_SCENE_ART_H")
    out.append("")
    out.append("#include <stdint.h>")
    out.append("")
    for name, (w, rows) in GRIDS.items():
        out.append(f"#define ART_{name.upper()}_W {w}")
        out.append(f"#define ART_{name.upper()}_H {len(rows)}")
        out.append(f"static const uint8_t art_{name}[{w * len(rows)}] = {{")
        vals = []
        for r in rows:
            vals.extend(CH[ch] for ch in r)
        for i in range(0, len(vals), 20):
            out.append("    " + ", ".join(str(v) for v in vals[i:i + 20]) + ",")
        out.append("};")
        out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(root, "src", "assets", "scene_art.h"), "w") as f:
        f.write(emit())
    print(f"wrote src/assets/scene_art.h: {len(GRIDS)} sprites, "
          f"{sum(w * len(r) for w, r in GRIDS.values())} px total")
    for name, (w, rows) in GRIDS.items():
        print(f"  {name}: {w}x{len(rows)}")
