#!/usr/bin/env python3
"""Generate src/assets/scene_art.h: palette-indexed sprites for the scene
engine (src/scene.c). All art is original, drawn on the pixel grids below.

Usage: python3 tools/gen_sprite_art.py

Sprite maps hold palette indices (see P_* in src/scene.h); 0 = transparent.
Char map:
  '.' transparent   'c' P_CLOUD    'm' P_MOON     'f' P_DARK (foliage)
  't' P_BLD (trunk) 'w' P_WHITE    'k' P_DARK     'p' P_COLLAR
  'a' P_ACC         'g' P_GLOW     'b' P_BLD      '2' P_BLD2
"""
import os

CH = {
    '.': 0, 'c': 7, 'm': 11, 'f': 13, 't': 4, 'w': 12, 'k': 13,
    'p': 14, 'a': 15, 'g': 6, 'b': 4, '2': 5,
}

GRIDS = {}

def grid(name, rows):
    w = len(rows[0])
    for r in rows:
        assert len(r) == w, f"{name}: row width {len(r)} != {w}"
    GRIDS[name] = (w, rows)

